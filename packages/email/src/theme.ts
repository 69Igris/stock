/**
 * Build RFC 8058 one-click unsubscribe headers. Pass the per-recipient HTTPS
 * unsubscribe URL (and optionally a mailto:). The endpoint must accept a POST
 * returning a blank 200 for this to be valid (see the unsubscribe routes).
 */
export function buildListUnsubscribeHeaders(
  unsubscribeUrl: string,
  mailto?: string,
): Record<string, string> {
  const parts: string[] = [];
  if (mailto) parts.push(`<mailto:${mailto}>`);
  parts.push(`<${unsubscribeUrl}>`);
  return {
    "List-Unsubscribe": parts.join(", "),
    "List-Unsubscribe-Post": "List-Unsubscribe=One-Click",
  };
}
