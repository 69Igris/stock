/**
 * Video Studio — the timeline DSL ("the choreographer's language").
 *
 * A brief becomes a Timeline. A Timeline is an ordered list of Scenes plus
 * global audio/brand settings. Every render + compose + prompt-edit operates
 * on this single structure, so "make scene 3 longer / swap the music / add a
 * voiceover" are just mutations of the JSON.
 */
import { z } from "zod";

export const AspectRatio = z.enum(["9:16", "1:1", "16:9"]);
export type AspectRatio = z.infer<typeof AspectRatio>;

export const BrandTheme = z.enum(["cream", "dark"]); // cream = v3 social; dark = Terminal Luxe (product)
export type BrandTheme = z.infer<typeof BrandTheme>;

/** What kind of scene the "crew" renders. */
export const SceneType = z.enum([
  "hook", // big opening line (pattern interrupt)
  "point", // one idea: headline + optional subtext
  "cards", // a titled list of 2–4 cards
  "stat", // a single large number reveal
  "quote", // founder/quote card
  "kinetic", // kinetic typography (words animate in sequence)
  "dataviz", // animated chart/bar reveal from data
  "veo", // AI B-roll generated by Veo (Vertex)
  "screen", // an imported screen-recording clip (ScreenStudio/CapCut)
  "talkinghead", // an imported face-cam clip + lower-third + captions
  "cta", // closing call-to-action + usemoney.ai pill
]);
export type SceneType = z.infer<typeof SceneType>;

export const Motion = z.enum([
  "static",
  "kenburns-in",
  "kenburns-out",
  "pan-left",
  "pan-right",
  "rise", // text rises + fades in
  "pop", // text pops/scales in
]);
export type Motion = z.infer<typeof Motion>;

export const Transition = z.enum([
  "cut",
  "crossfade",
  "slide",
  "whippan",
  "zoom",
]);
export type Transition = z.infer<typeof Transition>;

export const VoiceLang = z.enum(["hi-IN", "en-IN", "en-US"]);
export type VoiceLang = z.infer<typeof VoiceLang>;

/** Per-scene voiceover line (synthesized with Google TTS, or user-recorded path). */
export const Voiceover = z.object({
  text: z
    .string()
    .describe("Narration for this scene. Keep it short — ~2.5 words/sec."),
  lang: VoiceLang.default("hi-IN"),
  voice: z
    .string()
    .optional()
    .describe("Override TTS voice name; else env default for lang."),
  audioPath: z
    .string()
    .optional()
    .describe("If set, use this recorded audio instead of TTS."),
});
export type Voiceover = z.infer<typeof Voiceover>;

export const StatSpec = z.object({
  value: z.string().describe("The big number, e.g. '93%' or '₹1.8 lakh cr'."),
  label: z.string().optional(),
  kicker: z.string().optional(),
});

export const DataPoint = z.object({ label: z.string(), value: z.number() });

export const Scene = z.object({
  id: z.string(),
  type: SceneType,
  durationSec: z.number().min(0.8).max(60).default(3),
  // Text content (used by hook/point/cards/quote/kinetic/cta)
  kicker: z.string().optional(),
  headline: z
    .string()
    .optional()
    .describe(
      "Main line. Use *word* for serif-italic accent, ==word== for gold highlight.",
    ),
  subtext: z.string().optional(),
  bullets: z.array(z.string()).max(4).optional(),
  stat: StatSpec.optional(),
  data: z.array(DataPoint).optional().describe("For dataviz scenes."),
  // Media
  mediaPath: z
    .string()
    .optional()
    .describe("For 'screen'/'talkinghead': path to an existing video/image."),
  veoPrompt: z
    .string()
    .optional()
    .describe("For 'veo': text prompt for the B-roll clip."),
  // Look + movement
  motion: Motion.default("rise"),
  transitionIn: Transition.default("crossfade"),
  // Audio
  voiceover: Voiceover.optional(),
  // Compliance — appears as fine print on finance scenes
  disclaimer: z
    .boolean()
    .default(false)
    .describe("Render the short SEBI disclaimer on this scene."),
});
export type Scene = z.infer<typeof Scene>;

export const MusicSpec = z.object({
  track: z
    .string()
    .describe("A key in MUSIC_DIR (e.g. 'corporate-lofi') or a file path."),
  gainDb: z.number().default(-20),
  duckUnderVoiceover: z.boolean().default(true),
});
export type MusicSpec = z.infer<typeof MusicSpec>;

export const Timeline = z.object({
  title: z.string(),
  aspect: AspectRatio.default("9:16"),
  fps: z.number().int().default(30),
  brandTheme: BrandTheme.default("cream"),
  scenes: z.array(Scene).min(1),
  music: MusicSpec.optional(),
  captions: z
    .object({
      enabled: z.boolean().default(true),
      fromVoiceover: z.boolean().default(true),
    })
    .default({ enabled: true, fromVoiceover: true }),
  watermark: z
    .boolean()
    .default(true)
    .describe("UseMoney AI watermark bottom-right."),
  globalDisclaimer: z
    .string()
    .default("Education only · not investment advice · not a SEBI RIA")
    .describe(
      "Shown on the final frame / CTA; per-scene disclaimers use the short form.",
    ),
});
export type Timeline = z.infer<typeof Timeline>;

/** Result of any render/compose step. */
export const RenderResult = z.object({
  path: z.string(),
  durationSec: z.number(),
  width: z.number(),
  height: z.number(),
  note: z.string().optional(),
});
export type RenderResult = z.infer<typeof RenderResult>;

export const DIMENSIONS: Record<AspectRatio, { w: number; h: number }> = {
  "9:16": { w: 1080, h: 1920 },
  "1:1": { w: 1080, h: 1080 },
  "16:9": { w: 1920, h: 1080 },
};
