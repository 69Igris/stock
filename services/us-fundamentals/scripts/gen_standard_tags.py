"""Regenerate `packages/core/src/us-fundamentals/edgartools-standard-tags.ts`.

The TypeScript read seam maps edgartools' `standard_concept` values onto the
`FinancialStatement` shape. Those values come from `standard_tags` in
`edgar/xbrl/standardization/gaap_mappings.json` — a 3.7 MB file regenerated by
upstream on every release, since it carries per-tag `company_count` /
`first_year` statistics. Nothing in the TypeScript tree can observe that file,
so the vocabulary is exported here and pinned on both sides.

Run from the service root with the venv active:

    python scripts/gen_standard_tags.py
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import edgar
from edgar.xbrl import standardization

#: Repo-root-relative path of the generated module.
TARGET = Path("packages/core/src/us-fundamentals/edgartools-standard-tags.ts")


def mappings_path() -> Path:
    """`gaap_mappings.json` inside the INSTALLED edgartools, not a vendored copy."""
    return Path(standardization.__file__).parent / "gaap_mappings.json"


def standard_tags() -> list[str]:
    """Every value `standard_concept` can take, sorted and de-duplicated."""
    payload = json.loads(mappings_path().read_bytes())
    return sorted({t for v in payload.values() for t in (v.get("standard_tags") or [])})


def gaap_mappings_sha256() -> str:
    return hashlib.sha256(mappings_path().read_bytes()).hexdigest()


def render(tags: list[str], version: str, sha: str) -> str:
    body = "\n".join(f'  "{t}",' for t in tags)
    return f'''/**
 * GENERATED — do not hand-edit.
 *
 * Every value edgartools {version} can put in `standard_concept`: the union of
 * `standard_tags` across `edgar/xbrl/standardization/gaap_mappings.json`.
 *
 * This is the vocabulary the Python writer uses as the KEYS of the stored
 * `standardized` blob, so it is the vocabulary `US_CONCEPT_TO_STATEMENT_FIELD`
 * must be spelled in. It exists so that mismatch is a FAILING TEST rather than
 * a statement that silently renders one field.
 *
 * Regenerate with `services/us-fundamentals/scripts/gen_standard_tags.py`.
 * `tests/test_standard_tags_fixture.py` fails when the installed library and
 * this file disagree, which is how an edgartools upgrade announces itself.
 *
 * sha256(gaap_mappings.json) = {sha}
 */
export const US_EDGARTOOLS_VERSION = "{version}";

export const US_EDGARTOOLS_GAAP_MAPPINGS_SHA256 =
  "{sha}";

export const US_EDGARTOOLS_STANDARD_TAGS: readonly string[] = [
{body}
];
'''


def main() -> int:
    repo_root = Path(__file__).resolve().parents[3]
    target = repo_root / TARGET
    tags = standard_tags()
    target.write_text(render(tags, edgar.__version__, gaap_mappings_sha256()))
    print(f"wrote {target} — {len(tags)} tags, edgartools {edgar.__version__}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
