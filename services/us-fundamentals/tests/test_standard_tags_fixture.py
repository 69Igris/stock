"""The generated TS vocabulary fixture must match the INSTALLED edgartools.

`packages/core/src/us-fundamentals/edgartools-standard-tags.ts` is the only
thing on the TypeScript side that can see what `standard_concept` may contain,
and it is a snapshot. This test is what makes the snapshot trustworthy: an
edgartools upgrade that changes `gaap_mappings.json` fails HERE, next to the
version pin, instead of silently re-opening the defect that made every US
statement render as revenue and nothing else.

`gaap_mappings.json` is regenerated by upstream on every release — it carries
per-tag `company_count` / `first_year` statistics — so this WILL fire on
upgrade. That is the point. The remedy is to re-run
`scripts/gen_standard_tags.py`, re-read the diff, and re-check
`US_CONCEPT_TO_STATEMENT_FIELD` against it.
"""

from __future__ import annotations

import re
from pathlib import Path

import edgar

from scripts.gen_standard_tags import TARGET, gaap_mappings_sha256, render, standard_tags

REPO_ROOT = Path(__file__).resolve().parents[3]
FIXTURE = REPO_ROOT / TARGET


def _fixture_text() -> str:
    assert FIXTURE.exists(), f"generated fixture missing at {FIXTURE}"
    return FIXTURE.read_text()


def test_the_fixture_lists_exactly_the_installed_vocabulary() -> None:
    text = _fixture_text()
    block = text.split("US_EDGARTOOLS_STANDARD_TAGS: readonly string[] = [", 1)[1]
    listed = re.findall(r'^\s*"([^"]+)",$', block.split("];", 1)[0], re.MULTILINE)

    live = standard_tags()
    # Premise: neither side is empty, or the equality below is vacuous.
    assert len(live) > 200, f"extracted only {len(live)} tags from the installed library"
    assert len(listed) > 200, f"fixture lists only {len(listed)} tags"
    assert listed == live, (
        "fixture is stale — re-run services/us-fundamentals/scripts/gen_standard_tags.py; "
        f"missing={sorted(set(live) - set(listed))[:10]} "
        f"extra={sorted(set(listed) - set(live))[:10]}"
    )


def test_the_fixture_records_the_pinned_version_and_mappings_hash() -> None:
    text = _fixture_text()
    assert f'US_EDGARTOOLS_VERSION = "{edgar.__version__}"' in text
    assert gaap_mappings_sha256() in text


def test_the_fixture_is_byte_identical_to_what_the_generator_emits() -> None:
    """No hand-edit, no drift in the surrounding prose — the file is generated."""
    expected = render(standard_tags(), edgar.__version__, gaap_mappings_sha256())
    assert _fixture_text() == expected, (
        "fixture differs from generator output — it was hand-edited, or the "
        "generator changed without regenerating. Re-run scripts/gen_standard_tags.py."
    )
