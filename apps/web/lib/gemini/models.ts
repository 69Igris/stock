/**
 * Gemini LLM Integration - Model Configuration and Management
 *
 * This file handles model selection (Flash vs Pro), thinking mode configuration,
 * retry logic with exponential backoff, and generation parameter management.
 */

import { getVertexAIClient, type GeminiGenerativeModel } from "./client";
import { geminiLogger as logger } from "@usemoney/logger";
import type { QueryMode, ModelConfig } from "./types";

/**
 * Model configurations for fast and advanced modes
 */
export const MODEL_CONFIG: Record<QueryMode, ModelConfig> = {
  fast: {
    modelName: "gemini-2.5-flash",
    enableThinking: false,
    generationConfig: {
      temperature: 0.7, // Balanced creativity
      topP: 0.95, // Nucleus sampling
      topK: 40, // Top-K sampling
      maxOutputTokens: 2048, // Lower for faster responses
    },
  },
  advanced: {
    modelName: "gemini-2.5-pro",
    enableThinking: true, // ALWAYS enabled for advanced mode
    generationConfig: {
      temperature: 0.9, // Higher creativity for deep analysis
      topP: 0.95,
      topK: 40,
      maxOutputTokens: 16384, // Higher for detailed responses
      // Thinking mode configuration for Gemini 2.5 Pro
      // thinkingBudget: minimum 1024, maximum 24576 tokens
      // Higher budget = more reasoning depth but slower response
      thinkingConfig: {
        thinkingBudget: 8192, // Allocate 8K tokens for thinking process
      },
    },
  },
};

/**
 * Default retry / timeout constants (used when the corresponding env var is
 * unset). Exported so tests assert the SAME values the runtime uses.
 */
export const DEFAULT_MAX_RETRIES = 3;
export const DEFAULT_TIMEOUT_MS = 30000;

/**
 * Resolve the retry count: explicit arg → GEMINI_MAX_RETRIES env → default.
 * A non-positive / non-finite parse falls back to the default so a bad env
 * value can never disable retries or spin a negative loop.
 */
export function resolveMaxRetries(maxRetries?: number): number {
  if (maxRetries !== undefined) return maxRetries;
  const parsed = parseInt(
    process.env.GEMINI_MAX_RETRIES || String(DEFAULT_MAX_RETRIES),
    10
  );
  return Number.isFinite(parsed) && parsed > 0 ? parsed : DEFAULT_MAX_RETRIES;
}

/**
 * Resolve the wall-clock timeout: explicit arg → GEMINI_TIMEOUT_MS env →
 * default. Guards against a non-finite / non-positive env value.
 */
export function resolveTimeoutMs(timeout?: number): number {
  if (timeout !== undefined) return timeout;
  const parsed = parseInt(
    process.env.GEMINI_TIMEOUT_MS || String(DEFAULT_TIMEOUT_MS),
    10
  );
  return Number.isFinite(parsed) && parsed > 0 ? parsed : DEFAULT_TIMEOUT_MS;
}

/**
 * Exponential backoff for retry attempt `attempt` (0-indexed): 1s, 2s, 4s, 8s…
 */
export function retryBackoffMs(attempt: number): number {
  return Math.pow(2, attempt) * 1000;
}

/**
 * Get Gemini model instance for the specified query mode
 *
 * @param mode - Query mode (fast or advanced)
 * @returns Generative model instance configured for the mode
 */
export function getGeminiModel(mode: QueryMode): GeminiGenerativeModel {
  const vertexAI = getVertexAIClient();
  const config = MODEL_CONFIG[mode];

  logger.info(
    {
      mode,
      model: config.modelName,
      thinking: config.enableThinking,
    },
    "Initializing Gemini model"
  );

  return vertexAI.getGenerativeModel({
    model: config.modelName,
    generationConfig: config.generationConfig,
  });
}

/**
 * Generate content with retry logic and exponential backoff
 *
 * This function provides robust error handling for Gemini API calls:
 * - Retries failed requests up to maxRetries times
 * - Uses exponential backoff (1s, 2s, 4s, 8s...)
 * - Logs all attempts and errors
 * - Throws the last error if all retries fail
 *
 * @param model - Gemini model instance
 * @param prompt - Input prompt for generation
 * @param maxRetries - Maximum number of retry attempts
 * @returns Generated text response
 * @throws Error if all retries fail
 */
export async function generateWithRetry(
  model: GeminiGenerativeModel,
  prompt: string,
  maxRetries?: number
): Promise<string> {
  const retries = resolveMaxRetries(maxRetries);
  let lastError: Error | null = null;

  for (let attempt = 0; attempt < retries; attempt++) {
    try {
      logger.info(
        {
          attempt: attempt + 1,
          maxRetries: retries,
          promptLength: prompt.length,
        },
        "Generating content with Gemini"
      );

      const result = await model.generateContent(prompt);
      const response = result.response;

      // Extract text from the first candidate
      const candidate = response.candidates?.[0];

      if (!candidate) {
        throw new Error("No response candidate generated by Gemini");
      }

      // Extract text from all parts and join them
      const text = (candidate.content?.parts ?? [])
        .map((part) => part.text ?? "")
        .join("");

      logger.info(
        {
          attempt: attempt + 1,
          responseLength: text.length,
        },
        "Gemini generation successful"
      );

      return text;
    } catch (error) {
      lastError = error as Error;

      logger.warn(
        {
          attempt: attempt + 1,
          maxRetries: retries,
          error: lastError.message,
        },
        "Gemini generation attempt failed"
      );

      // Don't wait on the last attempt
      if (attempt < retries - 1) {
        const delay = retryBackoffMs(attempt); // 1s, 2s, 4s, 8s...
        logger.info({ delay }, "Waiting before retry");
        await new Promise((resolve) => setTimeout(resolve, delay));
      }
    }
  }

  logger.error(
    {
      attempts: retries,
      error: lastError?.message,
    },
    "All Gemini generation attempts failed"
  );

  throw lastError || new Error("Failed to generate content after retries");
}

/**
 * Generate content with timeout
 *
 * Wraps generateWithRetry with a timeout to prevent hanging requests
 *
 * @param model - Gemini model instance
 * @param prompt - Input prompt
 * @param timeout - Timeout in milliseconds (default from env)
 * @returns Generated text or throws timeout error
 */
export async function generateWithTimeout(
  model: GeminiGenerativeModel,
  prompt: string,
  timeout?: number
): Promise<string> {
  const timeoutMs = resolveTimeoutMs(timeout);

  return Promise.race([
    generateWithRetry(model, prompt),
    new Promise<string>((_, reject) =>
      setTimeout(
        () =>
          reject(new Error(`Gemini request timed out after ${timeoutMs}ms`)),
        timeoutMs
      )
    ),
  ]);
}

/**
 * Stream content from Gemini token-by-token (MONEY-291).
 *
 * Yields text deltas as Vertex produces them so the chat can render the
 * narrative as it arrives instead of waiting for the whole response. Mirrors
 * generateWithRetry's text extraction; a hard wall-clock deadline aborts a
 * stuck stream so a hung generation can't hang the request.
 *
 * @param model - Gemini model instance
 * @param prompt - Input prompt
 * @param timeout - Wall-clock cap in ms (default from env)
 */
export async function* generateContentStreamText(
  model: GeminiGenerativeModel,
  prompt: string,
  timeout?: number
): AsyncGenerator<string, void, unknown> {
  const timeoutMs = resolveTimeoutMs(timeout);
  const deadline = Date.now() + timeoutMs;

  const result = await model.generateContentStream(prompt);
  for await (const chunk of result.stream) {
    if (Date.now() > deadline) {
      throw new Error(`Gemini stream timed out after ${timeoutMs}ms`);
    }
    const parts = chunk.candidates?.[0]?.content?.parts ?? [];
    const text = parts.map((part) => part.text ?? "").join("");
    if (text) yield text;
  }
}

/**
 * Estimate token count for a string
 *
 * This is a rough approximation. The actual token count may vary.
 * Rule of thumb: 1 token ≈ 4 characters for English text
 *
 * @param text - Input text
 * @returns Estimated token count
 */
export function estimateTokenCount(text: string): number {
  return Math.ceil(text.length / 4);
}

/**
 * Generate content with safety settings
 *
 * Adds safety settings to prevent harmful content generation
 *
 * @param model - Gemini model instance
 * @param prompt - Input prompt
 * @returns Generated text response
 */
export async function generateWithSafety(
  model: GeminiGenerativeModel,
  prompt: string
): Promise<string> {
  // Safety settings can be added here if needed
  // For now, we rely on Gemini's default safety settings
  return generateWithRetry(model, prompt);
}
