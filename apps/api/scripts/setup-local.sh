#!/bin/bash
# ============================================
# UseMoney API - Local Development Setup
# ============================================
# Run this script to set up local development environment
#
# Usage: ./scripts/setup-local.sh
# ============================================

set -e

echo "╔════════════════════════════════════════════╗"
echo "║  UseMoney Local Development Setup         ║"
echo "╚════════════════════════════════════════════╝"
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

PROJECT_ID="stock-book-483718"
REGION="asia-south1"
STORAGE_BUCKET="stockbook-content-local"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
API_DIR="$(dirname "$SCRIPT_DIR")"

# -----------------------------
# 1. Check prerequisites
# -----------------------------
echo -e "${YELLOW}1. Checking prerequisites...${NC}"

if ! command -v gcloud &> /dev/null; then
    echo -e "${RED}Error: gcloud CLI not installed${NC}"
    echo "Install from: https://cloud.google.com/sdk/docs/install"
    exit 1
fi

if ! command -v yarn &> /dev/null; then
    echo -e "${RED}Error: yarn not installed${NC}"
    exit 1
fi

echo -e "${GREEN}   ✓ All prerequisites installed${NC}"

# -----------------------------
# 2. Set GCP project
# -----------------------------
echo -e "${YELLOW}2. Setting GCP project...${NC}"
gcloud config set project $PROJECT_ID
echo -e "${GREEN}   ✓ Project set to $PROJECT_ID${NC}"

# -----------------------------
# 3. Create Storage Bucket (Local)
# -----------------------------
echo -e "${YELLOW}3. Creating storage bucket for local dev...${NC}"

if gsutil ls -b gs://$STORAGE_BUCKET &>/dev/null; then
    echo -e "${GREEN}   ✓ Bucket $STORAGE_BUCKET already exists${NC}"
else
    echo "   Creating bucket $STORAGE_BUCKET..."
    gsutil mb -p $PROJECT_ID -l $REGION gs://$STORAGE_BUCKET

    # Set CORS for local development
    cat > /tmp/cors-local.json << 'CORS_EOF'
[
  {
    "origin": ["http://localhost:3000", "http://localhost:3001", "http://localhost:8080"],
    "method": ["GET", "PUT", "POST", "DELETE", "HEAD"],
    "responseHeader": ["Content-Type", "Authorization", "Content-Length", "Accept-Encoding"],
    "maxAgeSeconds": 3600
  }
]
CORS_EOF
    gsutil cors set /tmp/cors-local.json gs://$STORAGE_BUCKET
    rm /tmp/cors-local.json

    echo -e "${GREEN}   ✓ Bucket $STORAGE_BUCKET created with CORS${NC}"
fi

# -----------------------------
# 4. Create .env.local file
# -----------------------------
echo -e "${YELLOW}4. Creating .env.local file...${NC}"

if [ -f "$API_DIR/.env.local" ]; then
    echo -e "${YELLOW}   .env.local already exists. Backing up to .env.local.bak${NC}"
    cp "$API_DIR/.env.local" "$API_DIR/.env.local.bak"
fi

cat > "$API_DIR/.env.local" << 'EOF'
# ============================================
# UseMoney API - Local Development
# ============================================
# Generated by setup-local.sh
# ============================================

# Environment
NODE_ENV=development
PORT=8080

# CORS Origins (local)
WEB_URL=http://localhost:3000
ADMIN_URL=http://localhost:3001

# Database (MongoDB Atlas)
# Get from: MongoDB Atlas Dashboard
DATABASE_URL=mongodb+srv://USER:PASSWORD@cluster.mongodb.net/stockbook_dev?retryWrites=true&w=majority

# Redis (local or Upstash)
# For local: redis://localhost:6379
# For Upstash: Get from Upstash Dashboard
REDIS_URL=redis://localhost:6379

# Clerk Authentication
# Get from: https://dashboard.clerk.com → API Keys
CLERK_SECRET_KEY=sk_test_YOUR_KEY_HERE

# GCP Configuration
GCP_PROJECT_ID=stock-book-483718
GCP_STORAGE_BUCKET=stockbook-content-local

# Option 1: Use local service account file
# Download from GCP Console → IAM → Service Accounts → Keys
GOOGLE_APPLICATION_CREDENTIALS=/path/to/stock-book-483718-key.json

# Option 2: Use base64 encoded key (comment out GOOGLE_APPLICATION_CREDENTIALS)
# GCP_SERVICE_ACCOUNT_KEY_BASE64=BASE64_ENCODED_KEY

# Rate Limiting
RATE_LIMIT_WINDOW_MS=60000
RATE_LIMIT_MAX_REQUESTS=100

# Logging
LOG_LEVEL=debug
EOF

echo -e "${GREEN}   ✓ Created .env.local${NC}"

# -----------------------------
# 5. Download service account key
# -----------------------------
echo -e "${YELLOW}5. Setting up GCP service account key...${NC}"

SA_EMAIL="stockbook-api@${PROJECT_ID}.iam.gserviceaccount.com"
KEY_FILE="$API_DIR/stock-book-483718-key.json"

if [ -f "$KEY_FILE" ]; then
    echo -e "${YELLOW}   Key file already exists at $KEY_FILE${NC}"
else
    echo "   Downloading service account key..."
    gcloud iam service-accounts keys create "$KEY_FILE" \
        --iam-account="$SA_EMAIL" 2>/dev/null || {
        echo -e "${RED}   Failed to create key. You may need to create it manually in GCP Console.${NC}"
    }

    if [ -f "$KEY_FILE" ]; then
        echo -e "${GREEN}   ✓ Downloaded key to $KEY_FILE${NC}"

        # Update .env.local with correct path
        sed -i '' "s|/path/to/stock-book-483718-key.json|$KEY_FILE|g" "$API_DIR/.env.local"
    fi
fi

# -----------------------------
# 6. Install dependencies
# -----------------------------
echo -e "${YELLOW}6. Installing dependencies...${NC}"
cd "$API_DIR/../.." # Go to monorepo root
yarn install
echo -e "${GREEN}   ✓ Dependencies installed${NC}"

# -----------------------------
# 7. Generate Prisma client
# -----------------------------
echo -e "${YELLOW}7. Generating Prisma client...${NC}"
yarn db:generate
echo -e "${GREEN}   ✓ Prisma client generated${NC}"

# -----------------------------
# Done
# -----------------------------
echo ""
echo "╔════════════════════════════════════════════╗"
echo "║  Local Setup Complete!                     ║"
echo "╚════════════════════════════════════════════╝"
echo ""
echo "Next steps:"
echo "  1. Edit apps/api/.env.local with your actual values:"
echo "     - DATABASE_URL (MongoDB Atlas connection string)"
echo "     - REDIS_URL (local Redis or Upstash URL)"
echo "     - CLERK_SECRET_KEY (from Clerk Dashboard)"
echo ""
echo "  2. Start the development server:"
echo "     yarn workspace @stockbook/api-server dev"
echo ""
echo "  3. Test the API:"
echo "     curl http://localhost:8080/health"
echo ""
